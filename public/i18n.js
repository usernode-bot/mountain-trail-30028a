  // Longest tag first so a prefix match picks the most specific entry.
  var SUPPORTED = ['id', 'en'];
  var DEFAULT = 'en';

  function subtag(tag) {
    if (typeof tag !== 'string' || !tag) return null;
    var m = tag.toLowerCase().match(/^([a-z]{2,3})(?:[-_][a-z0-9]+)*/);
    return m ? m[1] : null;
  }

  // stored: the hiker's own in-app choice ('en' | 'id' | other), wins.
  // platformLocale: the Homeroom account setting, null when unset.
  // deviceLang: navigator.language. null means "no preference", never
  // English, so the device fallback still works.
  function resolveLang(stored, platformLocale, deviceLang) {
    var candidates = [stored, subtag(platformLocale) || null, deviceLang];
    for (var i = 0; i < candidates.length; i++) {
      var s = subtag(candidates[i]);
      if (!s) continue;
      for (var j = 0; j < SUPPORTED.length; j++) {
        if (s === SUPPORTED[j]) return SUPPORTED[j];
      }
    }
    return DEFAULT;
  }

  function fill(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, function (m, k) {
      return vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m;
    });
  }

  // t(lang, key, vars): the key's string in that language, English as the
  // fallback, and the key itself when neither has it (so a typo is visible).
  function t(lang, key, vars) {
    var dict = STRINGS[lang] || STRINGS[DEFAULT];
    var text = dict[key] !== undefined ? dict[key] : STRINGS[DEFAULT][key];
    if (text === undefined) return key;
    return fill(text, vars);
  }

  function has(lang, key) {
    return STRINGS[lang] !== undefined && STRINGS[lang][key] !== undefined;
  }

  function keys(lang) {
    return Object.keys(STRINGS[lang] || {});
  }

  return {
    resolveLang: resolveLang,
    t: t,
    has: has,
    keys: keys,
    DEFAULT: DEFAULT,
    SUPPORTED: SUPPORTED,
  };
